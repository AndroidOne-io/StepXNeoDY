# 当前台词里只确认这两种字是口头填充词；不对「那」「了」「的」等一刀切。
OMIT = {'呢', '吧'}


def build_captions(shots, norm):
    assert set(CAPTIONS) == {s['i'] for s in shots}, '镜头变更后需要重新校对字幕'
    result = []
    for s in shots:
        original = norm(s['text'])
        cursor = 0
        for text in CAPTIONS[s['i']].split('|'):
            indices = []
            for word in norm(text):
                while cursor < len(original) and original[cursor] != word and original[cursor] in OMIT:
                    cursor += 1
                assert cursor < len(original) and original[cursor] == word, (s['i'], text, cursor)
                indices.append(cursor)
                cursor += 1
            assert indices, (s['i'], text)
            start = max(0, s['chars'][indices[0]] - 0.05)
            end = min(s['end'], s['chars'][indices[-1]] + 0.32)
            result.append([round(start, 3), text, s['i'], round(end, 3)])
        assert all(word in OMIT for word in original[cursor:]), (s['i'], original[cursor:])
    for a, b in zip(result, result[1:]):
        a[3] = min(a[3], b[0])
    return result
