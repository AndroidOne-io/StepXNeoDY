// ------------------------------------------------------------------ 4 任务进度连续播放，按口播关键词分段变速对齐四个节点
function rescueProgress(ctx, t) {
  // 原片节点取卡片开始出现的帧，避免到「叫车」时动画已提前完成四项。
  const marks = [
    [wt(4, '自己') - 0.05, 234.8],
    [EV.c4net - 0.04, 235.35],
    [EV.c4chg - 0.04, 235.9],
    [EV.c4car - 0.04, 236.3],
    [EV.c4back - 0.04, 236.85],
    [S[4].end, 239.9],
  ];
  let i = 0;
  while (i < marks.length - 2 && t >= marks[i + 1][0]) i++;
  const [a, b] = [marks[i], marks[i + 1]];
  const rate = (b[1] - a[1]) / (b[0] - a[0]);
  const ts = lerp(a[1], b[1], clamp((t - a[0]) / (b[0] - a[0]), 0, 1));
  full(ctx, 'a02', ts, { rate, crop: CASE_CROP, z: 1 });
}
VIS[4] = (ctx, t) => cutList(ctx, t, [
  [S[4].start, clip('a02', 131.53, 134.2, { push: 0.05 })],
  [wt(4, '自己') - 0.05, rescueProgress],
]);

